    private void loadLoggedInUserDetails() {

    String email = UserLogin.loggedInUserEmail;

    if (email == null || email.trim().isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "No logged-in user found."
        );
        return;
    }

    String query = "SELECT fullname, email, phone, age, dob, address, gender, bloodgroup "
                 + "FROM user WHERE email=?";

    try {

        Class.forName("com.mysql.cj.jdbc.Driver");

        Connection conn = DriverManager.getConnection(
                "jdbc:mysql://127.0.0.1:3306/DoctorConsultationSystem",
                "root",
                "system123"
        );

        PreparedStatement pst = conn.prepareStatement(query);

        pst.setString(1, email);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            // Full Name
            jTextField1.setText(rs.getString("fullname"));

            // Email
            jTextField2.setText(rs.getString("email"));

            // Phone
            jTextField3.setText(rs.getString("phone"));

            // Age
            jTextField4.setText(rs.getString("age"));

            // DOB
            java.sql.Date dob = rs.getDate("dob");

            if (dob != null) {

                java.util.Calendar cal =
                        java.util.Calendar.getInstance();

                cal.setTime(dob);

                int day = cal.get(java.util.Calendar.DAY_OF_MONTH);
                int month = cal.get(java.util.Calendar.MONTH) + 1;
                int year = cal.get(java.util.Calendar.YEAR);

                String dobText = String.format(
                        "%02d-%02d-%04d",
                        day,
                        month,
                        year
                );

                jTextField5.setText(dobText);
            }

            // Address
            jTextField6.setText(rs.getString("address"));

            // Gender
            String gender = rs.getString("gender");

            if (gender != null) {
                jComboBox1.setSelectedItem(gender);
            }

            // Blood Group
            String bloodgroup = rs.getString("bloodgroup");

            if (bloodgroup != null) {
                jComboBox2.setSelectedItem(bloodgroup);
            }

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Logged-in user details not found."
            );
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (Exception e) {

        e.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                "Error loading user details:\n"
                + e.getMessage()
        );
    }
}

