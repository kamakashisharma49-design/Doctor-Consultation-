    private void jButton9ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton9ActionPerformed

        

    

        // ==========================================
        // GET VALUES FROM TEXT FIELDS
        // ==========================================
        String fullname = jTextField1.getText().trim();
        String email = jTextField2.getText().trim();
        String phone = jTextField3.getText().trim();
        String age = jTextField4.getText().trim();
        String dobText = jTextField5.getText().trim();
        String address = jTextField6.getText().trim();

        String gender = jComboBox1.getSelectedItem().toString();
        String bloodgroup = jComboBox2.getSelectedItem().toString();

        // ==========================================
        // BASIC VALIDATION
        // ==========================================
        if (fullname.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter your full name."
            );

            return;
        }

        if (email.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter your email."
            );

            return;
        }

        // ==========================================
        // PHONE VALIDATION
        // ==========================================
        if (phone.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter your phone number."
            );

            return;
        }

        if (!phone.matches("\\d{10}")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Phone number must contain exactly 10 digits."
            );

            return;
        }

        // ==========================================
        // AGE VALIDATION
        // ==========================================
        if (age.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter your age."
            );

            return;
        }

        try {

            Integer.parseInt(age);

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Age must contain numbers only."
            );

            return;
        }

        // ==========================================
        // DOB VALIDATION
        // ==========================================
        if (dobText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter your Date of Birth."
            );

            return;
        }

        java.sql.Date dob;

        try {

            /*
         * DOB TEXT FIELD:
         *
         * DD-MM-YYYY
         *
         * Example:
         * 15-08-2005
             */
            String[] parts = dobText.split("-");

            if (parts.length != 3) {
                throw new Exception();
            }

            int day = Integer.parseInt(parts[0]);
            int month = Integer.parseInt(parts[1]);
            int year = Integer.parseInt(parts[2]);

            // Basic validation
            if (day < 1 || day > 31
                    || month < 1 || month > 12
                    || year < 1900 || year > 2100) {

                throw new Exception();
            }

            // Convert DD-MM-YYYY to YYYY-MM-DD
            String mysqlDate
                    = year + "-"
                    + String.format("%02d", month) + "-"
                    + String.format("%02d", day);

            dob = java.sql.Date.valueOf(mysqlDate);

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Invalid Date of Birth.\n\n"
                    + "Please enter DOB in this format:\n"
                    + "DD-MM-YYYY\n\n"
                    + "Example: 15-08-2005"
            );

            return;
        }

        // ==========================================
        // GENDER VALIDATION
        // ==========================================
        if (jComboBox1.getSelectedIndex() == 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select your gender."
            );

            return;
        }

        // ==========================================
        // BLOOD GROUP VALIDATION
        // ==========================================
        if (jComboBox2.getSelectedIndex() == 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select your blood group."
            );

            return;
        }

        // ==========================================
        // GET LOGGED-IN USER EMAIL
        // ==========================================
        String oldEmail = UserLogin.loggedInUserEmail;

        if (oldEmail == null || oldEmail.trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "No logged-in user found."
            );

            return;
        }

        // ==========================================
        // UPDATE DATABASE
        // ==========================================
        String query
                = "UPDATE user SET "
                + "fullname=?, "
                + "email=?, "
                + "phone=?, "
                + "age=?, "
                + "dob=?, "
                + "address=?, "
                + "gender=?, "
                + "bloodgroup=? "
                + "WHERE email=?";

        try {

            Class.forName("com.mysql.cj.jdbc.Driver");

            Connection conn = DriverManager.getConnection(
                    "jdbc:mysql://127.0.0.1:3306/DoctorConsultationSystem",
                    "root",
                    "system123"
            );

            PreparedStatement pst = conn.prepareStatement(query);

            // ==========================================
            // SET DATABASE VALUES
            // ==========================================
            pst.setString(1, fullname);
            pst.setString(2, email);
            pst.setString(3, phone);
            pst.setString(4, age);

            // DATE column
            pst.setDate(5, dob);

            pst.setString(6, address);
            pst.setString(7, gender);
            pst.setString(8, bloodgroup);

            // WHERE condition
            pst.setString(9, oldEmail);

            // ==========================================
            // EXECUTE
            // ==========================================
            int rowsUpdated = pst.executeUpdate();

            if (rowsUpdated > 0) {

                // Update login session
                UserLogin.loggedInUserName = fullname;
                UserLogin.loggedInUserEmail = email;

                JOptionPane.showMessageDialog(
                        this,
                        "Profile updated successfully!"
                );

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "User not found."
                );
            }

            pst.close();
            conn.close();

        } catch (Exception e) {

            e.printStackTrace();

            JOptionPane.showMessageDialog(
                    this,
                    "Error updating profile:\n"
                    + e.getMessage()
            );
        }

    }//GEN-LAST:event_jButton9ActionPerformed

