    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        try {
            // Read values from form
            String name = jTextField1.getText().trim();

            String email = jTextField2.getText().trim();

            String phone = jTextField5.getText().trim();

            String speciality = jComboBox1.getSelectedItem().toString();

            String experience = jTextField3.getText().trim();

            String fee = jTextField4.getText().trim();

            String address = jTextArea1.getText().trim();

            String gender = "";

            if ("Male".equalsIgnoreCase(gender)) {
                jRadioButton1.setSelected(true);
            } else if ("Female".equalsIgnoreCase(gender)) {
                jRadioButton2.setSelected(true);
            } else if ("Other".equalsIgnoreCase(gender)) {
                jRadioButton3.setSelected(true);
            }

            // Fetch logged-in doctor's record
            ResultSet rs = DBLoader.executeQuery(
                    "select * from doctor where email='"
                    + DoctorLogin.loggedInDoctorEmail + "'");

            if (rs.next()) {

                rs.updateString("fullname", name);

                rs.updateString("email", email);

                rs.updateString("speciality", speciality);

                rs.updateString("experience", experience);

                rs.updateString("address", address);

                rs.updateString("consultationFee", fee);

                rs.updateString("phoneNumber", phone);

                rs.updateString("gender", gender);

                rs.updateRow();

                JOptionPane.showMessageDialog(this,
                        "Profile Updated Successfully.");
            } else {
                JOptionPane.showMessageDialog(this,
                        "Doctor Record Not Found.");
            }

        } catch (Exception ex) {
            ex.printStackTrace();

            JOptionPane.showMessageDialog(this,
                    "Error : " + ex.getMessage());
        }


    }//GEN-LAST:event_jButton1ActionPerformed

