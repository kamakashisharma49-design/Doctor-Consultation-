    private void loadDoctorDetails() {

        try {

            ResultSet rs = DBLoader.executeQuery(
                    "select * from doctor where email='"
                    + DoctorLogin.loggedInDoctorEmail + "'"
            );

            if (rs.next()) {

                String gender = rs.getString("gender");

                jTextField1.setText(rs.getString("fullname"));
                jTextField2.setText(rs.getString("email"));

                jComboBox1.setSelectedItem(
                        rs.getString("speciality")
                );

                jTextField3.setText(
                        rs.getString("experience")
                );

                jTextField4.setText(
                        rs.getString("consultationFee")
                );

                jTextArea1.setText(
                        rs.getString("address")
                );

                jTextField5.setText(
                        rs.getString("phoneNumber")
                );

                // Gender is optional, so check for null first
                if (gender != null) {

                    if (gender.equalsIgnoreCase("Male")) {
                        jRadioButton1.setSelected(true);

                    } else if (gender.equalsIgnoreCase("Female")) {
                        jRadioButton2.setSelected(true);

                    } else if (gender.equalsIgnoreCase("Other")) {
                        jRadioButton3.setSelected(true);
                    }
                }
            }

        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }

