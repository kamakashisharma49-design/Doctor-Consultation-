    private void addPlaceholder(JTextComponent component, String text) {

        Color normalColor = component.getForeground();
        Color placeholderColor = new Color(150, 150, 150);

        component.setForeground(placeholderColor);

        if (component instanceof JPasswordField) {
            ((JPasswordField) component).setText(text);
            ((JPasswordField) component).setEchoChar((char) 0);
        } else {
            component.setText(text);
        }

        component.addFocusListener(new java.awt.event.FocusAdapter() {

            @Override
            public void focusGained(java.awt.event.FocusEvent e) {

                if (component.getText().equals(text)) {

                    component.setText("");
                    component.setForeground(normalColor);

                    if (component instanceof JPasswordField) {
                        ((JPasswordField) component).setEchoChar('•');
                    }
                }
            }

            @Override
            public void focusLost(java.awt.event.FocusEvent e) {

                if (component.getText().trim().isEmpty()) {

                    component.setText(text);
                    component.setForeground(placeholderColor);

                    if (component instanceof JPasswordField) {
                        ((JPasswordField) component).setEchoChar((char) 0);
                    }
                }
            }
        });
    }

