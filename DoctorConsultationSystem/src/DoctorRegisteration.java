    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String fullName = jTextField1.getText().trim();
        String email = jTextField2.getText().trim();
        String password = String.valueOf(jPasswordField1.getPassword());
        String confirmPassword = String.valueOf(jPasswordField2.getPassword());
        String speciality = jComboBox1.getSelectedItem().toString();
        String experience = jTextField3.getText().trim();
        String address = jTextArea1.getText().trim();
        String consultationFee = jTextField4.getText().trim();

        try {

            // ==============================
            // 1. VALIDATE EMPTY FIELDS
            // ==============================
            if (fullName.isEmpty()
                    || email.isEmpty()
                    || password.isEmpty()
                    || confirmPassword.isEmpty()
                    || experience.isEmpty()
                    || address.isEmpty()
                    || consultationFee.isEmpty()
                    || speciality.equals("Select Speciality")) {

                JOptionPane.showMessageDialog(
                        this,
                        "Please enter all the mandatory fields."
                );

                return;
            }

            // ==============================
            // 2. CHECK PROFILE PICTURE
            // ==============================
            if (selectedImageFile == null) {

                JOptionPane.showMessageDialog(
                        this,
                        "Please select a profile picture."
                );

                return;
            }

            // ==============================
            // 3. CHECK PASSWORD MATCH
            // ==============================
            if (!password.equals(confirmPassword)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Password doesn't match."
                );

                return;
            }

            // ==============================
            // 4. CHECK TERMS & CONDITIONS
            // ==============================
            if (!jCheckBox1.isSelected()) {

                JOptionPane.showMessageDialog(
                        this,
                        "Please accept the Terms and Conditions to continue."
                );

                return;
            }

            // ==============================
            // 5. CHECK EMAIL ALREADY EXISTS
            // ==============================
            ResultSet rs = DBLoader.executeQuery(
                    "select * from doctor where email='" + email + "'"
            );

            if (rs.next()) {

                JOptionPane.showMessageDialog(
                        this,
                        "Email already exists. Please use another email."
                );

                return;
            }

            // ==============================
            // 6. SAVE PROFILE PICTURE
            // ==============================
            String profilePicturePath = saveProfilePicture();

            // ==============================
            // 7. INSERT DOCTOR
            // ==============================
            rs.moveToInsertRow();

            rs.updateString("fullname", fullName);
            rs.updateString("email", email);
            rs.updateString("pass", password);
            rs.updateString("speciality", speciality);
            rs.updateString("experience", experience);
            rs.updateString("address", address);
            rs.updateString("consultationFee", consultationFee);
            rs.updateString("profile_picture", profilePicturePath);

            rs.insertRow();

            // ==============================
            // 8. SUCCESS
            // ==============================
            JOptionPane.showMessageDialog(
                    this,
                    "Registration Successful!"
            );
            DoctorLogin register = new DoctorLogin();
            register.setVisible(true);
            this.dispose();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Registration failed:\n" + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );

            e.printStackTrace();
        }

    }//GEN-LAST:event_jButton1ActionPerformed
    private String saveProfilePicture() throws IOException {

        if (selectedImageFile == null) {
            return null;
        }

        // Create uploads folder
        File uploadsFolder = new File("uploads");

        if (!uploadsFolder.exists()) {
            uploadsFolder.mkdirs();
        }

        // Get extension
        String originalName = selectedImageFile.getName();

        String extension = "";

        int dotIndex = originalName.lastIndexOf(".");

        if (dotIndex > 0) {
            extension = originalName.substring(dotIndex);
        }

        // Unique filename
        String newFileName
                = "doctor_" + UUID.randomUUID() + extension;

        // Destination
        File destinationFile
                = new File(uploadsFolder, newFileName);

        // Copy image
        Files.copy(
                selectedImageFile.toPath(),
                destinationFile.toPath(),
                StandardCopyOption.REPLACE_EXISTING
        );

        return destinationFile.getPath();
    }
